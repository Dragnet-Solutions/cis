#!/usr/bin/env node
/**
 * Embeds the email templates (src/email-templates/html/*.html) in a TypeScript
 * module, so they ship inside the compiled package (dist/) with no file reads
 * at runtime — the API image carries only dist/.
 *
 *   node scripts/gen-email-templates.mjs           write templates.generated.ts
 *   node scripts/gen-email-templates.mjs --check   exit 1 if it is out of date
 *
 * A template's id is its file name up to the first "_" (F-01_firm-invitation.html → F-01).
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'email-templates');
const htmlDir = join(root, 'html');
const outFile = join(root, 'templates.generated.ts');

export function generate() {
  const files = readdirSync(htmlDir)
    .filter((f) => f.endsWith('.html'))
    .sort();
  const entries = files.map((f) => {
    const id = f.split('_')[0];
    const html = readFileSync(join(htmlDir, f), 'utf8');
    return `  ${JSON.stringify(id)}: ${JSON.stringify(html)},`;
  });
  return [
    '// GENERATED by scripts/gen-email-templates.mjs from html/*.html. Do not edit:',
    '// change the .html file and run `pnpm --filter @cis/domain email:templates`.',
    'export const TEMPLATE_HTML: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

const next = generate();
if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== next) {
    console.error(
      'templates.generated.ts is out of date: run `pnpm --filter @cis/domain email:templates`',
    );
    process.exit(1);
  }
} else {
  writeFileSync(outFile, next);
}
